"""Regenerate recompiled C++ for one region and sync only changed files into generated/<region>/.

Steps: merge SCE library bindings from ps2_analyzer and missed function starts from find_code_pointers.py into the
region config (build/work/<region>/merged.toml), run ps2_recomp into build/work/<region>/gen_tmp, then copy
changed/new files to generated/<region>/ and delete stale ones (keeps rebuilds incremental).

Adapted from KillzoneRecomp's tools/scripts/regen.py (GPL-3.0).
Usage: python scripts/regen.py [usa|eu]   (default usa)
"""
import filecmp, os, re, shutil, subprocess, sys, tomllib
from pathlib import Path

# Code generator settings proven by KillzoneRecomp: register locals (patch 0017), direct tail-jump dispatch and
# entry_* fragments folded into their functions (patch 0023).
os.environ.setdefault('PS2X_CODEGEN', 'locals')
os.environ.setdefault('PS2X_CODEGEN_DSP', '1')
os.environ.setdefault('PS2X_CODEGEN_FOLD', '1')

ROOT = Path(__file__).resolve().parents[1]
REGION = (sys.argv[1] if len(sys.argv) > 1 else "usa").lower()
CFG = ROOT / "config" / REGION / f"cnr_{REGION}.toml"
if not CFG.exists():
    sys.exit(f"[regen] no config {CFG}")
WORK = ROOT / "build" / "work" / REGION
_gen = tomllib.loads(CFG.read_text())["general"]
ELF = ROOT / _gen["input"]
GEN = ROOT / _gen["output"]
FUNCS_CSV = ROOT / _gen["ghidra_output"]
ANALYZER_TOML = ROOT / "config" / REGION / "analyzer.toml"
CODE_POINTERS = WORK / "code_pointers.txt"
REJECT = ROOT / "config" / REGION / "code_pointers_reject.txt"
MERGED = WORK / "merged.toml"
TMP = WORK / "gen_tmp"
LOG = WORK / "recomp.log"
BIN = ROOT / "build" / "ps2recomp"
RECOMP = Path(os.environ.get("CNR_RECOMP_EXE", BIN / "ps2xRecomp" / "RelWithDebInfo" / "ps2_recomp.exe"))
ANALYZER = BIN / "ps2xAnalyzer" / "RelWithDebInfo" / "ps2_analyzer.exe"


def merged_config() -> str:
    text = CFG.read_text()
    if not ANALYZER_TOML.exists():
        subprocess.run([str(ANALYZER), str(ELF), str(ANALYZER_TOML)], check=True, stdout=subprocess.DEVNULL)
    cfg = tomllib.loads(text)
    have = {s.split("@")[1].upper() for s in cfg["general"]["stubs"] if "@" in s}
    keep = set(cfg.get("cnr", {}).get("keep_recompiled", []))
    extra = [s for s in tomllib.loads(ANALYZER_TOML.read_text())["general"].get("stubs", [])
             if "@" in s and s.split("@")[1].upper() not in have and s.split("@")[0] not in keep]
    lines = "".join(f'  "{s}",\n' for s in extra)
    text = re.sub(r"(stubs = \[\n)", lambda m: m.group(1) + lines, text, count=1)
    # The config's paths are relative to the project root; ps2_recomp gets them absolute.
    text = re.sub(r'^output = .*$', lambda m: f'output = "{TMP.as_posix()}"', text, count=1, flags=re.M)
    text = re.sub(r'^input = .*$', lambda m: f'input = "{ELF.resolve().as_posix()}"', text, count=1, flags=re.M)
    text = re.sub(r'^ghidra_output = .*$', lambda m: f'ghidra_output = "{FUNCS_CSV.resolve().as_posix()}"',
                  text, count=1, flags=re.M)
    print(f"[regen] +{len(extra)} SCE library bindings from ps2_analyzer ({len(keep)} kept recompiled)")
    env = dict(os.environ, CNR_ELF=str(ELF), CNR_FUNCS_CSV=str(FUNCS_CSV), CNR_CODE_POINTERS=str(CODE_POINTERS),
               CNR_CODE_POINTERS_REJECT=str(REJECT))
    subprocess.run([sys.executable, "-I", str(ROOT / "scripts" / "find_code_pointers.py")], check=True, env=env)
    entries = [l.strip() for l in CODE_POINTERS.read_text().splitlines() if l.strip()]
    entry_line = "entry_points = [" + ", ".join(f'"{e}"' for e in entries) + "]\n"
    text = re.sub(r"(\[general\]\n)", lambda m: m.group(1) + entry_line, text, count=1)
    print(f"[regen] +{len(entries)} entry points from find_code_pointers")
    # Our own [cnr] table is not for ps2_recomp.
    return re.sub(r"\n\[cnr\]\n.*", "\n", text, flags=re.S)


def sync() -> None:
    GEN.mkdir(parents=True, exist_ok=True)
    new = {p.name for p in TMP.iterdir()}
    changed = 0
    for name in new:
        src, dst = TMP / name, GEN / name
        if not dst.exists() or not filecmp.cmp(src, dst, shallow=False):
            shutil.copy2(src, dst)
            changed += 1
    stale = [p for p in GEN.iterdir() if p.name not in new]
    for p in stale:
        p.unlink()
    print(f"[regen] {len(new)} files: {changed} changed/new, {len(stale)} removed")


def reject_data_candidates() -> None:
    """Record added entry points whose bodies failed to decode (data embedded in .text) so the next regen skips them."""
    cands = {int(l, 16) for l in CODE_POINTERS.read_text().split()}
    bad = set()
    for line in LOG.read_text(errors="replace").splitlines():
        m = re.search(r"\[error\] unhandled-instruction function=entry_([0-9a-f]+) ", line)
        if m and int(m.group(1), 16) in cands:
            bad.add(int(m.group(1), 16))
    old = REJECT.read_text().splitlines() if REJECT.exists() else ["# data mistaken for code; generated by regen.py"]
    have = {l.split()[0].lower() for l in old if l.strip() and not l.startswith("#")}
    new = [f"0x{v:08X}" for v in sorted(bad) if f"0x{v:08x}" not in have]
    if new:
        REJECT.write_text("\n".join(old + new) + "\n")
        print(f"[regen] {len(new)} entry points rejected as data (take effect next regen)")


def main() -> int:
    WORK.mkdir(parents=True, exist_ok=True)
    MERGED.write_text(merged_config())
    if TMP.exists():
        shutil.rmtree(TMP)
    with LOG.open("w") as f:
        r = subprocess.run([str(RECOMP), str(MERGED)], stdout=f, stderr=subprocess.STDOUT)
    if r.returncode != 0:
        print(f"[regen] ps2_recomp failed ({r.returncode}); see {LOG}")
        return r.returncode
    reject_data_candidates()
    sync()
    return 0


if __name__ == "__main__":
    sys.exit(main())
